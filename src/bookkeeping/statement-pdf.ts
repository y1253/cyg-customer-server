import PDFDocument from 'pdfkit';
import { periodLabel } from './report-pdf';

const BRAND = '#169F96';

const MONEY = (n: number): string =>
  n.toLocaleString('en-US', {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  });

const ISO = (d: Date | null): string => (d ? d.toISOString().slice(0, 10) : '');

export interface StatementPdfRow {
  postingDate: Date | null;
  pendingDate: Date | null;
  name: string | null;
  description: string;
  /** Our sign: + = money in (a payment on a card), − = money out (a purchase). */
  amount: number;
}

export interface StatementPdfInput {
  /** "Chase 4362 · Sep 2026" (`statementLabel`). */
  title: string;
  bankName: string | null;
  accountName: string | null;
  /** The book the statement belongs to ("Company1"). */
  owner: string;
  periodStart: Date | null;
  periodEnd: Date | null;
  currency: string | null;
  /** A card's balances are the amount OWED. */
  creditCard: boolean;
  opening: number | null;
  closing: number | null;
  rows: readonly StatementPdfRow[];
}

/**
 * The running balance after each row. A bank: + money in raises it. A card prints the
 * balance OWED, so money in (a payment) lowers it. Null when no opening is known.
 */
export function runningBalances(
  opening: number | null,
  rows: readonly { amount: number }[],
  creditCard: boolean,
): Array<number | null> {
  if (opening === null) return rows.map(() => null);
  let cents = Math.round(opening * 100);
  return rows.map((r) => {
    const a = Math.round(r.amount * 100);
    cents += creditCard ? -a : a;
    return cents / 100;
  });
}

/**
 * step12d: a bank-feed month (`source` PLAID) as a PDF that reads like a bank statement —
 * account, period, opening balance, every transaction with its running balance, closing
 * balance and the totals in / out. Bank-feed months have no stored file; this is built on
 * every open from the same rows the ledger shows.
 */
export function statementPdf(s: StatementPdfInput): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'LETTER', margin: 40 });
    const chunks: Buffer[] = [];
    doc.on('data', (c: Buffer) => chunks.push(c));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    const left = doc.page.margins.left;
    const bottom = () => doc.page.height - doc.page.margins.bottom;
    const balanceWord = s.creditCard ? 'balance owed' : 'balance';
    const cols = [
      { label: 'Posted', width: 58 },
      { label: 'Pending', width: 58 },
      { label: 'Description', width: 196 },
      { label: 'Amount', width: 104, align: 'right' as const },
      {
        label: s.creditCard ? 'Balance owed' : 'Balance',
        width: 116,
        align: 'right' as const,
      },
    ];
    const tableWidth = cols.reduce((n, c) => n + c.width, 0);

    doc
      .fillColor(BRAND)
      .font('Helvetica-Bold')
      .fontSize(17)
      .text(s.title, left);
    doc.fillColor('#333333').font('Helvetica').fontSize(10);
    const head = [
      s.bankName,
      s.accountName && s.accountName !== s.bankName ? s.accountName : null,
      s.owner,
    ].filter(Boolean);
    doc.text(head.join('  ·  '));
    doc.text(
      `${periodLabel(ISO(s.periodStart) || null, ISO(s.periodEnd) || null)}` +
        (s.currency ? `  ·  ${s.currency}` : ''),
    );
    doc
      .fillColor('#6B7280')
      .fontSize(8.5)
      .text(
        `From your bank feed (Plaid) — generated by CYG Finance on ${ISO(new Date())}. ` +
          'This is not a document issued by your bank.',
      );
    doc.moveDown(0.8);

    const totalIn = s.rows
      .filter((r) => r.amount > 0)
      .reduce((n, r) => n + Math.round(r.amount * 100), 0);
    const totalOut = s.rows
      .filter((r) => r.amount < 0)
      .reduce((n, r) => n - Math.round(r.amount * 100), 0);
    const summary: Array<[string, string]> = [
      [`Opening ${balanceWord}`, s.opening === null ? '—' : MONEY(s.opening)],
      [
        s.creditCard ? 'Payments and credits' : 'Money in',
        MONEY(totalIn / 100),
      ],
      [
        s.creditCard ? 'Purchases and charges' : 'Money out',
        MONEY(totalOut / 100),
      ],
      [`Closing ${balanceWord}`, s.closing === null ? '—' : MONEY(s.closing)],
      ['Transactions', String(s.rows.length)],
    ];
    doc.fillColor('#222222').fontSize(10);
    for (const [label, value] of summary) {
      const y = doc.y;
      doc.font('Helvetica').text(label, left, y, { width: 200 });
      doc.font('Helvetica-Bold').text(value, left + 200, y, {
        width: 120,
        align: 'right',
      });
      doc.y = y + 15;
    }
    doc.moveDown(0.8);

    const drawHeader = () => {
      const y = doc.y;
      doc.rect(left, y - 3, tableWidth, 16).fill(BRAND);
      let x = left;
      doc.fillColor('#FFFFFF').font('Helvetica-Bold').fontSize(8.5);
      for (const c of cols) {
        doc.text(c.label, x + 3, y, {
          width: c.width - 6,
          align: c.align ?? 'left',
        });
        x += c.width;
      }
      doc.y = y + 16;
    };
    drawHeader();

    const balances = runningBalances(s.opening, s.rows, s.creditCard);
    s.rows.forEach((r, i) => {
      const description =
        r.name && !r.description.toLowerCase().includes(r.name.toLowerCase())
          ? `${r.description}\n${r.name}`
          : r.description;
      const balance = balances[i];
      const cells = [
        ISO(r.postingDate),
        ISO(r.pendingDate),
        description,
        MONEY(r.amount),
        balance === null ? '' : MONEY(balance),
      ];
      doc.font('Helvetica').fontSize(8.5);
      const h =
        Math.max(
          ...cells.map((t, k) =>
            doc.heightOfString(t, { width: cols[k].width - 6 }),
          ),
        ) + 5;
      if (doc.y + h > bottom()) {
        doc.addPage();
        drawHeader();
      }
      const y = doc.y;
      if (i % 2 === 1) doc.rect(left, y - 2, tableWidth, h).fill('#F3F8F8');
      let x = left;
      doc.font('Helvetica').fontSize(8.5);
      cells.forEach((t, k) => {
        doc
          .fillColor(
            k === 3 ? (r.amount < 0 ? '#B42318' : '#067647') : '#222222',
          )
          .text(t, x + 3, y, {
            width: cols[k].width - 6,
            align: cols[k].align ?? 'left',
          });
        x += cols[k].width;
      });
      doc.y = y + h;
    });
    if (!s.rows.length) {
      doc
        .fillColor('#6B7280')
        .font('Helvetica-Oblique')
        .fontSize(9)
        .text('No posted transactions in this period.', left, doc.y + 4);
    }

    doc
      .moveDown(0.6)
      .font('Helvetica-Bold')
      .fontSize(10)
      .fillColor('#222222')
      .text(
        `Closing ${balanceWord}: ${s.closing === null ? '—' : MONEY(s.closing)}`,
        left,
        doc.y,
      );
    doc.end();
  });
}
